async function downloadPDF() {
    const { jsPDF } = window.jspdf;
    const doc = new jsPDF();
    const t = translations[currentLang];
    const name = el("user-name").value;
    const date = new Date().toLocaleDateString();

    doc.setFontSize(22);
    doc.text(t.pdfReport, 20, 30);
    doc.setFontSize(12);
    doc.text(`${name}`, 20, 40);
    doc.text(`${date}`, 20, 47);
    doc.line(20, 52, 190, 52);

    let yPos = 65;
    Object.keys(state.scores).forEach(key => {
        const score = state.scores[key];
        const sev = scales[key].severity.find(v => score <= v.max);
        doc.text(`${translations[currentLang].scales[key].name}: ${score}/${scales[key].max}`, 20, yPos);
        doc.text(`Severity: ${sev.label[currentLang]}`, 20, yPos + 7);
        yPos += 20;
    });

    doc.setFontSize(10);
    doc.text(t.pdfContact, 20, yPos + 10);
    doc.save(`${t.pdfReport}_${name}.pdf`);
}
// Function to save data to a local "Score Card" file in the browser
function captureUserData() {
    const name = el("user-name").value;
    const timestamp = new Date().toLocaleString();
    
    // Create the Score Card object
    const scoreCard = {
        userName: name,
        date: timestamp,
        scores: {
            depression: state.scores.phq9,
            anxiety: state.scores.gad7,
            distress: state.scores.k10
        },
        language: currentLang
    };

    // 1. Get existing data from storage or start a new list
    let history = JSON.parse(localStorage.getItem("mindcheck_history")) || [];
    
    // 2. Add the new score card
    history.push(scoreCard);
    
    // 3. Save it back to the browser's memory
    localStorage.setItem("mindcheck_history", JSON.stringify(history));
    
    console.log("Score Card saved locally for:", name);
}

