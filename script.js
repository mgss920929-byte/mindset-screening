const el = (id) => document.getElementById(id);

function setLanguage(lang) {
    currentLang = lang;
    const t = translations[lang];
    
    // Update UI text
    el("ui-subtitle").textContent = t.subtitle;
    el("ui-symptoms-title").textContent = t.symptomsTitle;
    el("ui-symptoms-list").innerHTML = t.symptomsList.map(s => `<li>• ${s}</li>`).join('');
    el("ui-pain-title").textContent = t.painTitle;
    el("ui-pain-desc").textContent = t.painDesc;
    el("ui-start-btn").textContent = t.startBtn;
    el("ui-tg-text").textContent = t.tgText;
    el("ui-who-title").textContent = t.whoTitle;
    el("user-name").placeholder = t.namePlaceholder;
    el("ui-continue-btn").textContent = t.continueBtn;
    el("ui-begin-scale-btn").textContent = t.beginScaleBtn;
    el("ui-time-ref").textContent = t.timeRef;
    el("ui-report-title").textContent = t.reportTitle;
    el("ui-dl-btn").textContent = t.dlBtn;
    el("ui-footer-tg").textContent = t.footerTg;
    el("ui-restart-btn").textContent = t.restartBtn;
    el("ui-progress-label").textContent = t.progressLabel;

    el("step-lang").classList.add("hidden");
    el("step-home").classList.remove("hidden");
}

function goToWelcome() {
    el("step-home").classList.add("hidden");
    el("step-welcome").classList.remove("hidden");
}

function startAssessment() {
  if (!el("user-name").value.trim()) return alert(currentLang === 'hi' ? "कृपया अपना नाम दर्ज करें" : "Please enter your name");
  el("step-welcome").classList.add("hidden");
  showTransition();
}

function showTransition() {
  const key = state.scaleKeys[state.scaleIndex];
  const t = translations[currentLang].scales[key];
  el("step-transition").classList.remove("hidden");
  el("trans-icon").textContent = key === 'phq9' ? "☁️" : key === 'gad7' ? "🌪️" : "🌊";
  el("trans-title").textContent = t.name;
  el("trans-desc").textContent = t.desc;
}

function beginScale() {
  el("step-transition").classList.add("hidden");
  el("step-quiz").classList.remove("hidden");
  el("progress-container").classList.remove("hidden");
  renderQuestion();
}

function renderQuestion() {
  const key = state.scaleKeys[state.scaleIndex];
  const q = scales[key].questions[currentLang][state.questionIndex];
  el("question-text").textContent = q;
  
  const progress = (state.answered / state.total) * 100;
  el("progress-bar").style.width = progress + "%";
  el("progress-text").textContent = Math.round(progress) + "%";

  el("options-container").innerHTML = "";
  translations[currentLang].options.forEach((opt, i) => {
    const btn = document.createElement("button");
    btn.textContent = opt;
    btn.className = "p-4 rounded-xl bg-slate-50 hover:bg-blue-50 border-2 border-transparent hover:border-blue-200 font-semibold text-left transition-all text-slate-700";
    btn.onclick = () => {
      btn.classList.add("ring-2", "ring-blue-500");
      setTimeout(() => answer(i), 150);
    };
    el("options-container").appendChild(btn);
  });
}

function answer(score) {
  const key = state.scaleKeys[state.scaleIndex];
  state.scores[key] += score;
  state.answered++;

  if (++state.questionIndex < scales[key].questions[currentLang].length) {
    renderQuestion();
  } else if (++state.scaleIndex < state.scaleKeys.length) {
    state.questionIndex = 0;
    el("step-quiz").classList.add("hidden");
    showTransition();
  } else {
    showResults();
  }
}

function showResults() {
  el("step-quiz").classList.add("hidden");
  el("progress-container").classList.add("hidden");
  el("step-results").classList.remove("hidden");
  renderAnalysis();
  renderChart();
}

function renderAnalysis() {
  el("detailed-analysis").innerHTML = "";
  Object.keys(state.scores).forEach(key => {
    const score = state.scores[key];
    const sev = scales[key].severity.find(v => score <= v.max);
    el("detailed-analysis").innerHTML += `
      <div class="p-5 rounded-2xl bg-white border border-slate-100 shadow-sm">
        <h3 class="font-bold text-slate-800">${translations[currentLang].scales[key].name} (${score}/${scales[key].max})</h3>
        <p class="text-sm ${sev.color} font-bold mb-1">${sev.label[currentLang]}</p>
      </div>`;
  });
}

